async function seedPricing() {
  console.log('🏷️  Starting pricing data seed...\n');

  // 1. Clear existing data (in order due to FK constraints)
  console.log('🗑️  Clearing existing pricing data...');

  const deletedTiers = await prisma.pricingTier.deleteMany();
  console.log(`   Deleted ${deletedTiers.count} pricing tiers`);

  const deletedServices = await prisma.service.deleteMany();
  console.log(`   Deleted ${deletedServices.count} services`);

  const deletedFaqs = await prisma.pricingFAQ.deleteMany();
  console.log(`   Deleted ${deletedFaqs.count} FAQs`);

  console.log('');

  // 2. Create services and tiers
  console.log('📦 Creating services and pricing tiers...');

  let totalTiers = 0;

  for (const serviceData of servicesData) {
    // Create service
    const service = await prisma.service.create({
      data: {
        name: serviceData.name,
        slug: serviceData.slug,
        description: serviceData.description,
        icon: serviceData.icon,
        isActive: true,
        displayOrder: serviceData.displayOrder,
      },
    });

    console.log(`   ✅ Created service: ${service.name} (${serviceData.tiers.length} tiers)`);

    // Create tiers for this service
    for (let i = 0; i < serviceData.tiers.length; i++) {
      const tierData = serviceData.tiers[i];

      await prisma.pricingTier.create({
        data: {
          serviceId: service.id,
          name: tierData.name,
          description: tierData.description,
          price: tierData.price,
          priceNote: tierData.priceNote,
          currency: 'VND',
          billingType: tierData.billingType,
          features: JSON.stringify(tierData.features),
          isPopular: tierData.isPopular || false,
          isRecommended: tierData.isRecommended || false,
          displayOrder: i + 1,
          ctaText: 'Liên hệ tư vấn',
          isActive: true,
        },
      });

      totalTiers++;
    }
  }

  console.log(`\n   📊 Total: ${servicesData.length} services, ${totalTiers} pricing tiers\n`);

  // 3. Re-link services to categories
  // Categories already exist in DB (not deleted by this script), but services lost their categoryId
  // Ensure Combo category exists (safety net if main seed hasn't run)
  await prisma.serviceCategory.upsert({
    where: { slug: 'combo-tiet-kiem-cat' },
    update: {},
    create: {
      name: 'Combo tiết kiệm',
      slug: 'combo-tiet-kiem-cat',
      description: 'Combo tiết kiệm khi mua nhiều dịch vụ cùng lúc - giảm 15-22% so với mua lẻ',
      icon: 'Package',
      displayOrder: 6,
      isActive: true,
    },
  });

  const serviceCategories = [
    { slug: 'website-ten-mien', serviceSlugs: ['ten-mien', 'hosting-server', 'chung-chi-ssl', 'thiet-ke-website', 'tinh-nang-bo-sung'] },
    { slug: 'marketing-truc-tuyen', serviceSlugs: ['seo', 'backlink-link-building', 'viet-bai-content-marketing', 'quang-cao-google-ads', 'quang-cao-facebook-ads', 'email-marketing', 'quan-ly-fanpage-mang-xa-hoi'] },
    { slug: 'ung-dung-di-dong', serviceSlugs: ['zalo-mini-app', 'ung-dung-mobile'] },
    { slug: 'phan-mem-he-thong', serviceSlugs: ['ung-dung-desktop', 'phat-trien-web-application-saas', 'api-tich-hop-he-thong', 'devops-ha-tang-cloud', 'kiem-thu-dam-bao-chat-luong-qa', 'phan-mem-crm-erp-hrm', 'tu-van-thue-lap-trinh-vien'] },
    { slug: 'thiet-ke-sang-tao', serviceSlugs: ['thiet-ke-logo-nhan-dien-thuong-hieu', 'thiet-ke-ui-ux'] },
    { slug: 'ai-tu-dong-hoa', serviceSlugs: ['chatbot-ai-bot', 'ai-machine-learning', 'tu-dong-hoa-rpa', 'bao-tri-ho-tro-ky-thuat'] },
    { slug: 'combo-tiet-kiem-cat', serviceSlugs: ['combo-website-khoi-nghiep', 'combo-ban-hang-marketing', 'combo-am-thuc-lam-dep', 'combo-y-te-giao-duc', 'combo-bds-du-lich', 'combo-branding-enterprise'] },
  ];

  console.log('📎 Re-linking services to categories...');
  let totalLinked = 0;
  for (const cat of serviceCategories) {
    const category = await prisma.serviceCategory.findUnique({ where: { slug: cat.slug } });
    if (category) {
      const result = await prisma.service.updateMany({
        where: { slug: { in: cat.serviceSlugs } },
        data: { categoryId: category.id },
      });
      if (result.count > 0) {
        console.log(`   ✅ Linked ${result.count} service(s) to ${category.name}`);
        totalLinked += result.count;
      }
    } else {
      console.log(`   ⚠️ Category not found: ${cat.slug} (run main seed.ts first)`);
    }
  }
  console.log(`\n   📊 Total: ${totalLinked} services linked to categories\n`);

  // 4. Create FAQs
  console.log('❓ Creating pricing FAQs...');

  for (const faqData of faqsData) {
    await prisma.pricingFAQ.create({
      data: {
        question: faqData.question,
        answer: faqData.answer,
        category: faqData.category,
        displayOrder: faqData.displayOrder,
        isActive: true,
      },
    });
  }

  console.log(`   ✅ Created ${faqsData.length} FAQs\n`);

  // Summary
  console.log('┌─────────────────────────────────────────────────────────────────┐');
  console.log('│                    PRICING SEED SUMMARY                         │');
  console.log('├─────────────────────────────────────────────────────────────────┤');
  console.log(`│ Services created:      ${String(servicesData.length).padStart(3)}                                    │`);
  console.log(`│ Pricing tiers created: ${String(totalTiers).padStart(3)}                                    │`);
  console.log(`│ Services linked:       ${String(totalLinked).padStart(3)}                                    │`);
  console.log(`│ FAQs created:          ${String(faqsData.length).padStart(3)}                                    │`);
  console.log('└─────────────────────────────────────────────────────────────────┘');

  console.log('\n✅ Pricing seed completed successfully!');

  // Clear Redis cache to ensure fresh data is served
  console.log('\n🔄 Clearing Redis pricing cache...');
  try {
    const redisUrl = process.env.REDIS_URL || 'redis://localhost:6379';
    const redisClient = new Redis(redisUrl);

    // Delete all pricing-related cache keys
    const keysToDelete = [
      PRICING_CACHE_KEYS.PUBLIC_SERVICES,
      PRICING_CACHE_KEYS.PUBLIC_FAQS,
      PRICING_CACHE_KEYS.PUBLIC_CATEGORIES,
    ];

    for (const key of keysToDelete) {
      await redisClient.del(key);
      console.log(`   ✅ Deleted cache key: ${key}`);
    }

    await redisClient.quit();
    console.log('   ✅ Redis pricing cache cleared successfully!');
  } catch (error) {
    console.warn('   ⚠️ Could not clear Redis cache (Redis may not be running):', error instanceof Error ? error.message : error);
    console.warn('   ⚠️ Cache will expire naturally based on TTL (60 seconds)');
  }
}

